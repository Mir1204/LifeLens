"""
Reports the class distribution for the three training datasets used by LifeLens.

Run from the backend folder:
    python -m app.ml.training.report_dataset_distributions

This script also prints a short note about the raw Kaggle sleep-health dataset
and whether it is used directly in model training.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from app.ml.training.training_utils import balance_classes


BASE_DIR = Path(__file__).resolve().parents[1]
DATA_DIR = BASE_DIR / "data"
RAW_DATA_PATH = DATA_DIR / "raw" / "sleep_health_lifestyle.csv"
STATIC_DATA_PATH = DATA_DIR / "static_stress_data.csv"
BURNOUT_DATA_PATH = DATA_DIR / "burnout_data.csv"
OVERSPEND_DATA_PATH = DATA_DIR / "overspend_data.csv"


def print_distribution(csv_path: Path, label_column: str) -> None:
    df = pd.read_csv(csv_path)
    counts = df[label_column].value_counts(dropna=False)
    total = len(df)

    print(f"{csv_path.name}")
    print(f"  rows: {total}")
    for label, count in counts.items():
        percentage = (count / total * 100) if total else 0
        print(f"  {label}: {count} ({percentage:.1f}%)")
    print()


def print_balanced_distribution(csv_path: Path, label_column: str) -> None:
    df = pd.read_csv(csv_path)
    balanced = balance_classes(df, label_column)
    counts = balanced[label_column].value_counts(dropna=False)
    total = len(balanced)

    print(f"{csv_path.name} balanced for training")
    print(f"  rows: {total}")
    for label, count in counts.items():
        percentage = (count / total * 100) if total else 0
        print(f"  {label}: {count} ({percentage:.1f}%)")
    print()


def main() -> None:
    print("LifeLens dataset class distribution report\n")
    print_distribution(STATIC_DATA_PATH, "stress_risk")
    print_balanced_distribution(STATIC_DATA_PATH, "stress_risk")
    print_distribution(BURNOUT_DATA_PATH, "burnout_risk")
    print_balanced_distribution(BURNOUT_DATA_PATH, "burnout_risk")
    print_distribution(OVERSPEND_DATA_PATH, "overspending_risk")
    print_balanced_distribution(OVERSPEND_DATA_PATH, "overspending_risk")

    print("Raw dataset usage note")
    if RAW_DATA_PATH.exists():
        print(f"  raw file found: {RAW_DATA_PATH.name}")
    else:
        print(f"  raw file not found: {RAW_DATA_PATH}")

    print(
        "  The raw sleep_health_lifestyle dataset is used indirectly: "
        "preprocess_kaggle_data.py reads it and produces static_stress_data.csv, "
        "and train_static_stress_model.py trains on that generated CSV."
    )
    print(
        "  The burnout and overspend models are trained from synthetic datasets "
        "generated by generate_synthetic_data.py, not from the raw Kaggle file."
    )


if __name__ == "__main__":
    main()